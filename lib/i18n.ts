// বাংলা: নির্বাচিত ভাষা অনুযায়ী UI text-এর অনুবাদ ফেরত দেয়।
export function translate(language: "bn" | "en", value: string): string {
    const normalized = value.trim();
    if (language === "en") {
        return enTranslations[normalized] ?? value;
    }
    return bnTranslations[normalized] ?? value;
}

// বাংলা: component-এ ব্যবহারযোগ্য translation helper সরবরাহ করে।
export function useT() {
    const { language } = useLanguage();
    return useCallback(
        (value: string) => translate(language, value),
        [language],
    );
}
